def km(a, b):
    (lo1, la1), (lo2, la2) = [(math.radians(x), math.radians(y)) for x, y in (a, b)]
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 2 * 6371 * math.asin(min(1, math.sqrt(h)))


class AgainstGPlates(SimpleTestCase):
    def test_GWS_의_PALEOMAP_과_3_km_안(self):
        m = paleo.model()
        for name, lon, lat, stops in GWS_PALEOMAP:
            plate = m.plate_at(lon, lat)
            for age, glon, glat in stops:
                with self.subTest(place=name, age=age):
                    got = m.carry(lon, lat, age, plate)
                    self.assertIn("lon", got)
                    self.assertLess(km((got["lon"], got["lat"]), (glon, glat)), 3)

    def test_판이_닿지_않는_연대는_옮기지_않는다(self):
        self.assertEqual(paleo.model().carry(-58.79, -62.22, 300)["reason"], "beyond")
